export function tenge(value: number) {
  return new Intl.NumberFormat("ru-KZ").format(value) + " ₸";
}

export function priceLabel(service: Service) {
  if (service.priceTo) return `${tenge(service.priceFrom)} – ${tenge(service.priceTo)}`;
  return `от ${tenge(service.priceFrom)}`;
}

