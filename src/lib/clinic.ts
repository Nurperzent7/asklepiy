export function doctorsFor(city?: string, service?: string) {
  return doctors.filter((doctor) => {
    const cityOk = !city || doctor.cities.includes(city as CityId);
    const serviceOk = !service || doctor.services.includes(service);
    return cityOk && serviceOk;
  });
}

export function servicesForCity(city: CityId) {
  return services.filter((service) => service.cities.includes(city));
}

const WEEKDAYS = ["вс", "пн", "вт", "ср", "чт", "пт", "сб"] as const;

export type SlotDay = { iso: string; label: string; times: string[] };

export function upcomingDays(city: CityId, count = 8): SlotDay[] {
  const branch = cityById(city);
  if (!branch) return [];
  const days: SlotDay[] = [];
  const cursor = new Date();
  cursor.setHours(12, 0, 0, 0);
  while (days.length < count) {
    cursor.setDate(cursor.getDate() + 1);
    const day = cursor.getDay();
    if (day === 0) continue;
    if (city !== "shymkent" && day === 6 && days.length > 5) continue;
    if (city !== "shymkent" && day === 6) {
      days.push({
        iso: cursor.toISOString().slice(0, 10),
        label: `${WEEKDAYS[day]}, ${cursor.getDate()} ${monthName(cursor.getMonth())}`,
        times: branch.slots.filter((time) => time < "15:00"),
      });
      continue;
    }
    days.push({
      iso: cursor.toISOString().slice(0, 10),
      label: `${WEEKDAYS[day]}, ${cursor.getDate()} ${monthName(cursor.getMonth())}`,
      times: branch.slots,
    });
  }
  return days;
}

function monthName(index: number) {
  return ["янв", "фев", "мар", "апр", "мая", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"][index];
}

export function isPhone(value: string) {
  const digits = value.replace(/\D/g, "");
  return digits.length === 11 && (digits.startsWith("7") || digits.startsWith("8"));
}
